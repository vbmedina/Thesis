# Invert the dictionaries to create a mapping from strain/ICM to their respective keys
inv_lst_strains = {}
for key, val in lst_strains.items():
    for v in val:
        if v in inv_lst_strains:
            print(f"Warning: {v} is already in the dictionary with value {inv_lst_strains[v]}")
        inv_lst_strains[v] = key

    if key in inv_lst_strains:
            print(f"Warning: {key} is already in the dictionary with value {inv_lst_strains[key]}")
    inv_lst_strains[key] = key

inv_lst_icm = {}
for key, val in lst_icm.items():
    for v in val:
        if v in inv_lst_icm:
            print(f"Warning: {v} is already in the dictionary with value {inv_lst_icm[v]}")
        inv_lst_icm[v] = key

    if key in inv_lst_icm:
            print(f"Warning: {key} is already in the dictionary with value {inv_lst_icm[key]}")
    inv_lst_icm[key] = key

combined_inv = {**inv_lst_strains, **inv_lst_icm}

# Create a 2D map

raw['ActualStrains'] = raw["verify_strain"].map(combined_inv)
