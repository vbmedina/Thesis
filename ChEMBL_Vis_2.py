sorted_columns = count_strains.sort_values(ascending=False).index

# Sort the grid by the count in each column
count_comps = grid.count(axis=1)
sorted_rows = count_comps.sort_values(ascending=False).index
grid = grid.loc[sorted_rows, sorted_columns]

